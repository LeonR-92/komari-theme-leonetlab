import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const projectRoot = process.cwd()
const sourceRoot = path.join(projectRoot, 'src')
const outputPath = path.join(sourceRoot, 'generated', 'iconRegistry.ts')
const supportedPrefixes = new Set(['carbon', 'icon-park-outline', 'lucide', 'tabler'])
const iconPattern = /\b(carbon|icon-park-outline|lucide|tabler):([a-z0-9-]+)/g
const sourceFilePattern = /\.(?:ts|vue)$/

async function collectSourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      if (entryPath === path.dirname(outputPath))
        continue
      files.push(...await collectSourceFiles(entryPath))
    }
    else if (sourceFilePattern.test(entry.name)) {
      files.push(entryPath)
    }
  }

  return files
}

function mergeAlias(collection, name, trail = new Set()) {
  if (trail.has(name))
    throw new Error(`Circular Iconify alias: ${name}`)

  const icon = collection.icons?.[name]
  if (icon)
    return { ...icon }

  const alias = collection.aliases?.[name]
  if (!alias)
    throw new Error(`Icon not found in ${collection.prefix}: ${name}`)

  trail.add(name)
  const parent = mergeAlias(collection, alias.parent, trail)
  trail.delete(name)

  return {
    ...parent,
    ...(alias.width === undefined ? {} : { width: alias.width }),
    ...(alias.height === undefined ? {} : { height: alias.height }),
    ...(alias.left === undefined ? {} : { left: alias.left }),
    ...(alias.top === undefined ? {} : { top: alias.top }),
    ...(alias.hFlip === undefined ? {} : { hFlip: Boolean(parent.hFlip) !== Boolean(alias.hFlip) }),
    ...(alias.vFlip === undefined ? {} : { vFlip: Boolean(parent.vFlip) !== Boolean(alias.vFlip) }),
    ...(alias.rotate === undefined ? {} : { rotate: ((parent.rotate || 0) + alias.rotate) % 4 }),
  }
}

function normalizeIcon(collection, name) {
  const icon = mergeAlias(collection, name)
  return {
    body: icon.body,
    width: icon.width ?? collection.width ?? 16,
    height: icon.height ?? collection.height ?? 16,
    ...(icon.left === undefined ? {} : { left: icon.left }),
    ...(icon.top === undefined ? {} : { top: icon.top }),
    ...(icon.hFlip ? { hFlip: true } : {}),
    ...(icon.vFlip ? { vFlip: true } : {}),
    ...(icon.rotate ? { rotate: icon.rotate } : {}),
  }
}

const sourceFiles = await collectSourceFiles(sourceRoot)
const requestedIcons = new Set()

for (const sourceFile of sourceFiles) {
  const source = await readFile(sourceFile, 'utf8')
  for (const match of source.matchAll(iconPattern))
    requestedIcons.add(`${match[1]}:${match[2]}`)
}

const collections = new Map()
const registry = {}
for (const fullName of [...requestedIcons].sort()) {
  const [prefix, name] = fullName.split(':')
  if (!supportedPrefixes.has(prefix))
    throw new Error(`Unsupported Iconify collection: ${prefix}`)

  if (!collections.has(prefix)) {
    const collectionPath = path.join(projectRoot, 'node_modules', '@iconify', 'json', 'json', `${prefix}.json`)
    collections.set(prefix, JSON.parse(await readFile(collectionPath, 'utf8')))
  }

  registry[fullName] = normalizeIcon(collections.get(prefix), name)
}

const generated = `/* eslint-disable style/comma-dangle, style/quote-props, style/quotes */\n// Generated by scripts/generate-icon-registry.mjs. Do not edit manually.\n`
  + `export const localIcons = ${JSON.stringify(registry, null, 2)} as const\n`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = await readFile(outputPath, 'utf8')
  }
  catch {
    // The mismatch below gives one consistent failure message.
  }

  if (current !== generated) {
    console.error('Local Iconify registry is stale. Run npm run icons:generate.')
    process.exitCode = 1
  }
  else {
    console.log(`Verified ${requestedIcons.size} local Iconify glyphs.`)
  }
}
else {
  await mkdir(path.dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated, 'utf8')
  console.log(`Generated ${requestedIcons.size} local Iconify glyphs.`)
}
